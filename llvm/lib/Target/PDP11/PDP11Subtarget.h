#ifndef LLVM_LIB_TARGET_PDP11_PDP11SUBTARGET_H
#define LLVM_LIB_TARGET_PDP11_PDP11SUBTARGET_H

#include "PDP11FrameLowering.h"
#include "PDP11ISelLowering.h"
#include "PDP11InstrInfo.h"
#include "PDP11SelectionDAGInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/IR/DataLayout.h"
#include "llvm/Target/TargetMachine.h"

#define GET_SUBTARGETINFO_HEADER
#include "PDP11GenSubtargetInfo.inc"

namespace llvm {

class PDP11Subtarget : public PDP11GenSubtargetInfo {
public:
  // This constructor initializes the data members to match that
  // of the specified triple.
  PDP11Subtarget(const Triple &TargetTriple, StringRef Cpu,
                 StringRef FeatureString, const TargetMachine &TM,
                 const TargetOptions &Options, CodeModel::Model CodeModel,
                 CodeGenOptLevel OptLevel);

  // ParseSubtargetFeatures - Parses features string setting specified
  // subtarget options.  Definition of function is auto generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  PDP11Subtarget &initializeSubtargetDependencies(StringRef CPU, StringRef FS);

  void initSubtargetFeatures(StringRef CPU, StringRef FS);

  bool enableMachineScheduler() const override { return true; }

  const PDP11InstrInfo *getInstrInfo() const override { return &InstrInfo; }

  const TargetFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }

  const PDP11RegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }

  const PDP11TargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }

  const PDP11SelectionDAGInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }

private:
  PDP11FrameLowering FrameLowering;
  PDP11InstrInfo InstrInfo;
  PDP11TargetLowering TLInfo;
  PDP11SelectionDAGInfo TSInfo;
};
} // namespace llvm

#endif // LLVM_LIB_TARGET_PDP11_PDP11SUBTARGET_H
